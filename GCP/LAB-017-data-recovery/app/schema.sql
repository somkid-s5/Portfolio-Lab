CREATE TABLE IF NOT EXISTS public.records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_ref TEXT NOT NULL UNIQUE,
    drill_id TEXT NOT NULL,
    title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 120),
    status TEXT NOT NULL CHECK (status IN ('NEW', 'REVIEW', 'APPROVED', 'REJECTED')),
    amount_cents BIGINT NOT NULL CHECK (amount_cents BETWEEN 0 AND 100000000),
    attachment_key TEXT NOT NULL UNIQUE,
    attachment_sha256 CHAR(64) NOT NULL,
    attachment_bytes INTEGER NOT NULL CHECK (attachment_bytes BETWEEN 1 AND 16384),
    state TEXT NOT NULL CHECK (state IN ('PENDING', 'READY')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX IF NOT EXISTS records_drill_id_record_ref_idx
    ON public.records (drill_id, record_ref);
